"""Instrucción:

Pide el año de nacimiento
Calcula la edad actual (año actual 2025)
Muestra la edad

Explicación:
Restas el año de nacimiento del año actual
"""

año_nacimiento = int(input("Digite su año de nacimiento: "))
edad = 2026 - año_nacimiento
print(f"Año de nacimiento es: {año_nacimiento} y su edad actual es: {edad}")