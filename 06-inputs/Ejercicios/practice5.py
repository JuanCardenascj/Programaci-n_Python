"""Instrucción:

Pide la edad al usuario con input()
Convierte la respuesta a entero con int()
Calcula cuántos años tendrá en 10 años
Muestra el resultado

Explicación:
int(input()) → Convierte el texto a número entero
"""

edad = int(input("Digite su edad: "))
edad_promedio = edad + 10
print(f"Su edad en 10 años sera de: {edad_promedio}")