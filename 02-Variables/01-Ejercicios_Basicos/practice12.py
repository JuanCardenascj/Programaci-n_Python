"""Instrucción:

Crea a = 15 y b = 4
Calcula suma, resta, multiplicación, división, división entera y módulo
Guarda cada resultado en una variable diferente
Muestra todas

Explicación:
// → División entera (sin decimales)
% → Módulo (resto de la división)
"""

a = 15
b = 4
suma = a + b
resta = a - b
multiplicacion = a * b
division = a / b
division_entera = a // b
modulo = a % b

print(f"Suma: {suma}")              # 19
print(f"Resta: {resta}")            # 11
print(f"Multiplicación: {multiplicacion}")  # 60
print(f"División: {division}")      # 3.75
print(f"División entera: {division_entera}")  # 3
print(f"Módulo: {modulo}")          # 3