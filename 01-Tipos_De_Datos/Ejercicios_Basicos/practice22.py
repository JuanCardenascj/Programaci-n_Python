"""Instrucción:

Crea dos variables x = 15 y y = 20
Compara: mayor, menor, igual, diferente, mayor o igual, menor o igual
Muestra cada resultado
"""

x = 15
y = 20
print(f"¿x es mayor que y? {x > y}")
print(f"¿x es menor que y? {x < y}")
print(f"¿x es igual a y? {x == y}")
print(f"¿x es diferente de y? {x != y}")
print(f"¿x es mayor o igual a y? {x >= y}")
print(f"¿x es menor o igual a y? {x <= y}")