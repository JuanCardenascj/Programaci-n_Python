"""Instrucción:

Crea una lista numeros = [1, 2, 3, 4, 5]
Usa un bucle for con else que se ejecute al final
Muestra "Bucle completado"

Explicación:
El bloque else se ejecuta después de que el bucle termine normalmente
"""

numeros = [1, 2, 3, 4, 5]

for numero in numeros:
    print(numero)
else:
    print("Bucle completado")