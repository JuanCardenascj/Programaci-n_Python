"""Instrucción:

Crea una lista nombres = ["Ana", "Luis", "Carlos", "Marta"]
Usa un bucle for para mostrar cada nombre
Muestra un saludo para cada nombre

Explicación:
for nombre in nombres: → Toma cada elemento de la lista
print(f"Hola {nombre}") → Muestra un mensaje para cada uno"""

nombres = ["Ana", "Luis", "Carlos", "Marta"]

for nombre in nombres:
    print(f"Hola {nombre}")