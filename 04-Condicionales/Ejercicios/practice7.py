"""Instrucción:

Crea numero = 5
Usa and para verificar si está entre 1 y 10
Si está, muestra "Está en el rango"
Si no, muestra "Está fuera del rango"

Explicación:
numero >= 1 and numero <= 10 → Ambas condiciones deben ser verdaderas
"""

numero = 5

if numero >= 1  and numero <= 10:
    print("Número en el rango")
else:
    print("Número fuera del rango")